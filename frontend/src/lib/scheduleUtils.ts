export const DOW_SHORT = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"] as const

export function isWeekendDay(day: string) {
  return day === "Saturday" || day === "Sunday"
}

export function isFridayDay(day: string) {
  return day === "Friday"
}

export function getShortDow(full: string) {
  const i = WEEK.indexOf(full as (typeof WEEK)[number])
  return i >= 0 ? DOW_SHORT[i] : full
}

/** Monday-start: row 0 = Monday, row 1 = Tuesday, ... */
export function longDayForLogRow(rowIndex0: number) {
  return WEEK[rowIndex0 % 7]!
}

/**
 * Check names whose Expected/Actual values are raw-minute integers. When
 * displayExpectedActual is invoked with one of these as ``checkName``, a
 * parenthesised ``"Xh Ym"`` companion is appended so reviewers don't have
 * to mentally divide by 60. Dollar-, count-, and boolean-valued checks
 * stay untouched.
 *
 * Kept in sync with the backend check names emitted by
 * ``backend/app/validate.py``.
 */
/** Strip leading ``3a — ``, ``12) ``, ``1 - `` style numbering from validator check names. */
export function stripLeadingCheckNumber(raw: string): string {
  return raw
    .replace(/^(\d+[a-z]?)\s*[-—.)]\s*/i, "")
    .replace(/^\d+\s*[-—.)]\s*/, "")
    .trim()
}

const MINUTE_VALUED_CHECK_NAMES = new Set<string>([
  "Weekly budget arithmetic",
  "Monthly minutes target",
  "Billable minutes = min(delivered, authorized)",
])

export function displayExpectedActual(v: unknown, checkName?: string): string {
  if (v === null || v === undefined) return "—"
  if (typeof v === "string" || typeof v === "number" || typeof v === "boolean") {
    const base = String(v)
    // Decorate integer minute values on the known minute-valued checks.
    if (
      typeof v === "number" &&
      Number.isFinite(v) &&
      checkName &&
      MINUTE_VALUED_CHECK_NAMES.has(stripLeadingCheckNumber(checkName))
    ) {
      return `${base} (${formatHoursMinutes(Math.trunc(v))})`
    }
    return base
  }
  try {
    return JSON.stringify(v)
  } catch {
    return String(v)
  }
}
